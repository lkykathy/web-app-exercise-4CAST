def seed_demo():
    for item in clothes:
        if not item["image_url"].strip():
            print(f"Skipped missing image URL: {item['name']}")
            continue
        existing = db.clothing_items.find_one({"name": item["name"]})
        if existing:
            print(f"Skipped existing item: {item['name']}")
            continue
        item_id = add_clothing(item)
        print(f"Added {item['name']}: {item_id}")


if __name__ == "__main__":
    seed_demo()
